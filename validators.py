"""
validators.py – Centralized input validation and sanitization for the OSG Portal.

Every user-supplied value MUST pass through one of these functions before it is
used in business logic, written to a data store, or echoed back to the client.

Rules:
  - Raise ValueError with a descriptive message on any violation.
  - Return the cleaned / normalized value on success.
  - Never swallow exceptions silently.
"""

import re
import os
import html
import datetime
from typing import List

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Maximum sizes
MAX_TEXT_DEFAULT   = 500    # characters
MAX_TEXT_SHORT     = 100    # username, staff name, sr_no …
MAX_TEXT_LONG      = 50000  # address, notes, remarks (notes grow over time as history is appended)
MAX_FILE_SIZE_MB   = 500    # 500 MB hard limit per uploaded file
MAX_FILE_SIZE_BYTES = MAX_FILE_SIZE_MB * 1024 * 1024
MAX_CLAIMS_PER_SUBMIT = 10  # maximum claim items in one submission
MAX_EXPORT_IDS     = 2000   # max claim IDs in one export request

# Allowed file extensions and their corresponding magic-byte signatures
ALLOWED_EXTENSIONS = {'.xlsx', '.xls', '.pdf', '.jpg', '.jpeg', '.png'}

# First-byte magic signatures {extension: [list of accepted byte-prefixes]}
# Using bytes objects so we can do startswith() checks on raw file bytes.
MAGIC_BYTES = {
    '.xlsx': [b'PK\x03\x04'],                    # ZIP/OOXML
    '.xls':  [b'\xd0\xcf\x11\xe0'],              # OLE2 Compound Document
    '.pdf':  [b'%PDF'],
    '.jpg':  [b'\xff\xd8\xff'],
    '.jpeg': [b'\xff\xd8\xff'],
    '.png':  [b'\x89PNG'],
}

# Allowed claim statuses – the ONLY values the system accepts from external input.
ALLOWED_STATUSES = {
    "submitted",
    "registered",
    "follow up",
    "repair completed",
    "replacement approved",
    "rejected",
    "cancelled",
    "closed",
    "no issue/oncall resolution",
    "no issue",
    "oncall resolution",
}


# Allowed search types for claim-status-lookup
ALLOWED_SEARCH_TYPES = {"mobile", "claim_id"}

# Characters that trigger spreadsheet formula injection when leading a cell value.
# We strip these from the START of any text destined for Google Sheets.
FORMULA_INJECTION_CHARS = ('=', '+', '-', '@', '\t', '\r')

# Pattern for claim IDs generated by the app (e.g. CLM-1713800400)
CLAIM_ID_RE = re.compile(r'^CLM-\d{6,15}$')

# Safe token pattern: exactly 64 lowercase hex characters
RESET_TOKEN_RE = re.compile(r'^[0-9a-f]{64}$')

# Date patterns we accept from the UI
DATE_FORMATS = ['%Y-%m-%d', '%d-%m-%Y']


# ---------------------------------------------------------------------------
# Core text sanitizer
# ---------------------------------------------------------------------------

def sanitize_text(
    value,
    max_len: int = MAX_TEXT_DEFAULT,
    allow_newlines: bool = False,
    field_name: str = "field",
    sheet_destined: bool = False,
) -> str:
    """
    Clean and validate a free-text user input.

    Steps:
      1. Coerce to str, strip whitespace.
      2. Remove null bytes and ASCII control characters (optionally keep newlines).
      3. HTML-escape to neutralise any embedded HTML/script.
      4. Reject if result exceeds max_len.
      5. If sheet_destined=True, strip leading formula-injection characters.

    Returns the sanitized string.
    Raises ValueError if any constraint is violated.
    """
    if value is None:
        return ""

    text = str(value).strip()

    # Remove null bytes
    text = text.replace('\x00', '')

    # Strip ASCII control characters (except newline/tab if allowed)
    if allow_newlines:
        # Keep \n and \r\n, remove other control chars
        text = re.sub(r'[\x01-\x08\x0b\x0c\x0e-\x1f\x7f]', '', text)
    else:
        # Remove ALL control characters including newline/tab
        text = re.sub(r'[\x00-\x1f\x7f]', '', text)
        text = text.strip()

    # HTML-escape to neutralise <script>, onclick=, etc.
    text = html.escape(text, quote=True)

    if len(text) > max_len:
        raise ValueError(
            f"{field_name} is too long (max {max_len} characters, got {len(text)})."
        )

    # Spreadsheet formula injection prevention
    if sheet_destined and text and text[0] in FORMULA_INJECTION_CHARS:
        text = "'" + text   # prefix with single-quote to force text interpretation

    return text


